# (1) 任意のリストに問題文のリストをセットする
word_list = ["どこで？", "だれが？", "いつ？"]

# (2) リストをセットする際に、特定の文字（例としてスペース）を加えて連結するメソッドを使う
# Pythonでは文字列を結合する場合、"区切り文字".join(リスト) メソッドを使います
combined_text = " ".join(word_list)

# (3) 表示する際に、先頭から最後から2番目までをスライスし、"."を足し算で追加する
# [0:-1] で「先頭から、最後から2番目の文字まで」を切り出せます
result_text = combined_text[0:-1] + "."

# 最終的な結果をprint文で表示
print(result_text)
